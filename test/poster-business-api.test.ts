import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import sharp from "sharp";
import { afterEach, describe, expect, it, vi } from "vitest";
import { processToolRunId } from "../src/agent-runtime/process-tools.js";
import { startCrtBusinessApi } from "../src/business-api/crt-server.js";
import type { ObjectStorageCapability } from "../src/business-api/object-storage.js";
import type { GenerateImageRequest } from "../src/business-api/openai-image-generation.js";

const input = { prompt: "A quiet paper poster", aspectRatio: "3:5" };
const cleanup: Array<() => Promise<void>> = [];
afterEach(async () => {
    for (const close of cleanup.splice(0).reverse()) await close();
});

async function setup(storage?: ObjectStorageCapability) {
    const directory = await mkdtemp(join(tmpdir(), "poster-api-"));
    cleanup.push(() => rm(directory, { recursive: true, force: true }));
    const bytes = await sharp({
        create: { width: 120, height: 200, channels: 3, background: "white" },
    })
        .png()
        .toBuffer();
    const generated = {
        bytes,
        mimeType: "image/png",
        outputFormat: "png" as const,
    };
    const generate = vi.fn(async (_request: GenerateImageRequest) => generated);
    const edit = vi.fn();
    async function start() {
        const api = await startCrtBusinessApi({
            directory,
            imageClient: { edit },
            generationClient: { generate },
            storage,
        });
        cleanup.push(api.close);
        return api;
    }
    const api = await start();
    return { api, start, generate, edit, generated, directory };
}

function post(
    url: string,
    body: unknown = input,
    key = "run-1",
    signal?: AbortSignal,
) {
    return fetch(`${url}/posters`, {
        method: "POST",
        headers: { "content-type": "application/json", "idempotency-key": key },
        body: JSON.stringify(body),
        signal,
    });
}

describe("poster rendering in the shared image Business API", () => {
    it.each(["run-1", processToolRunId("turn-1", 2)])(
        "persists successful claims across restarts and rejects changed content (%s)",
        async (key) => {
            const { api, start, generate, edit, generated, directory } =
                await setup();
            const response = await post(api.url, input, key);
            expect(response.status).toBe(200);
            const image = await response.json();
            expect(image).toEqual({
                url: `${api.url}/posters/${key}.png`,
                contentType: "image/png",
                width: 120,
                height: 200,
            });
            const firstDownload = await fetch(image.url);
            expect(Buffer.from(await firstDownload.arrayBuffer())).toEqual(
                generated.bytes,
            );
            await api.close();
            const restarted = await start();
            expect(
                await (await post(restarted.url, input, key)).json(),
            ).toEqual(image);
            const download = await fetch(`${restarted.url}/posters/${key}.png`);
            expect(Buffer.from(await download.arrayBuffer())).toEqual(
                generated.bytes,
            );
            expect(
                (
                    await post(
                        restarted.url,
                        { ...input, prompt: "Changed" },
                        key,
                    )
                ).status,
            ).toBe(409);
            expect(generate).toHaveBeenCalledOnce();
            expect(edit).not.toHaveBeenCalled();
            expect(
                await readFile(
                    join(directory, `poster-results/${key}.json`),
                    "utf8",
                ),
            ).not.toContain(input.prompt);
        },
    );

    it("returns the stored URL and expiry with the original generated bytes", async () => {
        const upload = vi.fn<ObjectStorageCapability["upload"]>(
            async (request) => ({
                provider: "test",
                bucket: "test",
                objectKey: request.objectKey,
                url: "https://assets.example/poster.png",
                urlAccess: "signed",
                urlExpiresAt: "2030-01-01T00:00:00.000Z",
                contentType: request.contentType,
                size: request.bytes.length,
            }),
        );
        const { api, generated } = await setup({ provider: "test", upload });
        const response = await post(api.url);
        expect(response.status).toBe(200);
        expect(await response.json()).toMatchObject({
            url: "https://assets.example/poster.png",
            expiresAt: "2030-01-01T00:00:00.000Z",
        });
        await post(api.url);
        expect(upload).toHaveBeenCalledExactlyOnceWith(
            {
                objectKey: "minimal-zine-poster/run-1.png",
                bytes: generated.bytes,
                contentType: "image/png",
                cacheControl: "private, max-age=31536000, immutable",
            },
            { signal: expect.any(AbortSignal) },
        );
    });

    it.each([
        { ...input, model: "caller-model" },
        { ...input, aspectRatio: "1:1" },
        { ...input, prompt: " " },
    ])(
        "rejects invalid internal requests before generation: %j",
        async (body) => {
            const { api, generate } = await setup();
            expect((await post(api.url, body)).status).toBe(400);
            expect((await post(api.url, input, "../unsafe")).status).toBe(400);
            expect(generate).not.toHaveBeenCalled();
        },
    );

    it.each(["provider", "storage", "raster"])(
        "does not regenerate after a %s failure, even after restart",
        async (stage) => {
            const upload = vi
                .fn<ObjectStorageCapability["upload"]>()
                .mockRejectedValue(new Error("private credential"));
            const { api, start, generate, generated } = await setup(
                stage === "storage" ? { provider: "test", upload } : undefined,
            );
            if (stage === "provider")
                generate.mockRejectedValue(new Error("private credential"));
            if (stage === "raster")
                generate.mockResolvedValue({
                    ...generated,
                    bytes: await sharp({
                        create: {
                            width: 100,
                            height: 100,
                            channels: 3,
                            background: "white",
                        },
                    })
                        .png()
                        .toBuffer(),
                });
            const response = await post(api.url);
            expect(response.status).toBe(503);
            expect(await response.json()).toEqual({
                error: { code: "POSTER_INCOMPLETE" },
            });
            await api.close();
            const restarted = await start();
            expect((await post(restarted.url)).status).toBe(503);
            expect(generate).toHaveBeenCalledOnce();
            expect(upload).toHaveBeenCalledTimes(stage === "storage" ? 1 : 0);
        },
    );

    it.each(["provider", "storage"])(
        "passes cancellation to %s and blocks concurrent or later resubmission",
        async (stage) => {
            const started = deferred();
            const aborted = deferred();
            const pending = (signal: AbortSignal | undefined) =>
                new Promise<never>((_resolve, reject) => {
                    signal?.addEventListener(
                        "abort",
                        () => {
                            aborted.resolve();
                            reject(new Error("cancelled"));
                        },
                        { once: true },
                    );
                    started.resolve();
                });
            const upload = vi.fn<ObjectStorageCapability["upload"]>(
                async (_request, options) => pending(options?.signal),
            );
            const { api, generate } = await setup(
                stage === "storage" ? { provider: "test", upload } : undefined,
            );
            if (stage === "provider")
                generate.mockImplementation(async (request) =>
                    pending(request.signal),
                );
            const controller = new AbortController();
            const result = post(
                api.url,
                input,
                "run-1",
                controller.signal,
            ).catch(() => undefined);
            try {
                await started.promise;
                expect((await post(api.url)).status).toBe(503);
            } finally {
                controller.abort();
            }
            await result;
            await aborted.promise;
            expect((await post(api.url)).status).toBe(503);
            expect(generate).toHaveBeenCalledOnce();
        },
    );
});

function deferred() {
    let resolve = () => {};
    const promise = new Promise<void>((complete) => {
        resolve = complete;
    });
    return { promise, resolve };
}
